//! `timer/kbuilds.h` registry editing and per-kernel profile files.
//!
//! One file per kernel lives in `timer/kbuilds/<release>.h`; the registry
//! header only carries the `#include` list and the pointer table. Adding a
//! kernel is `timer-extract <boot.img> --add`.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

use crate::derive::Facts;
use crate::error::{ExtractError, Result};

/// Repo-relative registry header.
pub const REGISTRY_PATH: &str = "timer/kbuilds.h";
const DIR_NAME: &str = "kbuilds";
const INCLUDE_MARKER: &str = "/* --- end build includes --- */";
const ENTRY_MARKER: &str = "/* --- end build entries --- */";

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FileState {
    Created,
    Updated,
    Unchanged,
}

impl FileState {
    pub fn label(self) -> &'static str {
        match self {
            FileState::Created => "created",
            FileState::Updated => "updated",
            FileState::Unchanged => "present",
        }
    }
}

#[derive(Debug)]
pub struct Registered {
    pub path: PathBuf,
    pub file: FileState,
    pub added_to_registry: bool,
}

/// C identifier of one kernel: the release string with every character that
/// cannot appear in an identifier replaced by `_`.
pub fn identifier(release: &str) -> String {
    let mut out = String::with_capacity(release.len());
    for ch in release.chars() {
        out.push(if ch.is_ascii_alphanumeric() { ch } else { '_' });
    }
    out
}

fn release_and_ident(facts: &Facts) -> Result<(&str, String)> {
    let release = facts
        .release
        .as_deref()
        .ok_or_else(|| ExtractError::new("image carries no kernel release string"))?;
    Ok((release, identifier(release)))
}

fn symbol(facts: &Facts, name: &str) -> u64 {
    facts.data_symbols.get(name).copied().unwrap_or(0)
}

/// Complete `timer/kbuilds/<release>.h` content.
pub fn render_profile(facts: &Facts) -> Result<String> {
    let (release, ident) = release_and_ident(facts)?;
    let mut out = String::new();
    let _ = writeln!(out, "/* {release}");
    let _ = writeln!(out, " * generated by timer-extract; do not edit. */");
    let _ = writeln!(out, "static const struct kbuild kbuild_{ident} = {{");
    let _ = writeln!(out, "    \"{release}\",");
    let _ = writeln!(
        out,
        "    0x{:x}ULL, 0x{:x}ULL, 0x{:x}ULL,",
        facts.text_base.wrapping_add(facts.sites.timer_site),
        facts.sites.timer_low21(),
        facts.sites.copy_process_low21()
    );
    let _ = writeln!(
        out,
        "    0x{:x}ULL, 0x{:x}ULL, 0x{:x}ULL, 0x{:x}ULL,",
        symbol(facts, "SELINUX_STATE_STATIC"),
        symbol(facts, "PANIC_ON_WARN_STATIC"),
        symbol(facts, "ROOT_USER_STATIC"),
        symbol(facts, "INIT_USER_NS_STATIC")
    );
    let _ = writeln!(
        out,
        "    0x{:x}ULL, 0x{:x}ULL,",
        symbol(facts, "INIT_UCOUNTS_STATIC"),
        symbol(facts, "INIT_GROUPS_STATIC")
    );
    let _ = writeln!(
        out,
        "    0x{:x}ULL, 0x{:x}ULL, 0x{:x}ULL, 0x{:x}ULL, 0x{:x}ULL, 0x{:x}U,",
        facts.layout.task_cred,
        facts.sizes.cred_req,
        facts.sizes.cred_alloc,
        facts.sizes.timer_alloc,
        facts.sizes.task_bytes,
        facts.layout.cred_uid
    );
    let _ = writeln!(out, "}};");
    Ok(out)
}

/// Insert `line` on its own line before the marker line.
fn insert_before(text: &str, marker: &str, line: &str) -> Result<String> {
    let at = text
        .find(marker)
        .ok_or_else(|| ExtractError::new(format!("registry marker missing: {marker}")))?;
    let start = text[..at].rfind('\n').map_or(0, |index| index + 1);
    let mut out = String::with_capacity(text.len() + line.len() + 1);
    out.push_str(&text[..start]);
    out.push_str(line);
    out.push('\n');
    out.push_str(&text[start..]);
    Ok(out)
}

/// True when the registry already lists this kernel.
pub fn is_registered(registry: &str, ident: &str) -> bool {
    registry.contains(&format!("&kbuild_{ident},"))
}

/// Add the `#include` and the table entry for one kernel.
pub fn register(registry: &str, release: &str, ident: &str) -> Result<(String, bool)> {
    let mut out = registry.to_string();
    let mut changed = false;
    let include = format!("#include \"{DIR_NAME}/{release}.h\"");
    if !out.contains(&include) {
        out = insert_before(&out, INCLUDE_MARKER, &include)?;
        changed = true;
    }
    if !is_registered(&out, ident) {
        out = insert_before(&out, ENTRY_MARKER, &format!("    &kbuild_{ident},"))?;
        changed = true;
    }
    Ok((out, changed))
}

/// Write the profile file and register it.
pub fn apply(registry: &Path, facts: &Facts) -> Result<Registered> {
    let (release, ident) = release_and_ident(facts)?;
    let dir = registry
        .parent()
        .unwrap_or_else(|| Path::new("."))
        .join(DIR_NAME);
    std::fs::create_dir_all(&dir)
        .map_err(|err| ExtractError::new(format!("cannot create {}: {err}", dir.display())))?;
    let path = dir.join(format!("{release}.h"));
    let body = render_profile(facts)?;
    let file = match std::fs::read_to_string(&path) {
        Ok(old) if old == body => FileState::Unchanged,
        Ok(_) => {
            std::fs::write(&path, &body)
                .map_err(|err| ExtractError::new(format!("cannot write {}: {err}", path.display())))?;
            FileState::Updated
        }
        Err(_) => {
            std::fs::write(&path, &body)
                .map_err(|err| ExtractError::new(format!("cannot write {}: {err}", path.display())))?;
            FileState::Created
        }
    };

    let current = std::fs::read_to_string(registry)
        .map_err(|err| ExtractError::new(format!("cannot read {}: {err}", registry.display())))?;
    let (updated, added_to_registry) = register(&current, release, &ident)?;
    if added_to_registry {
        std::fs::write(registry, updated)
            .map_err(|err| ExtractError::new(format!("cannot write {}: {err}", registry.display())))?;
    }
    Ok(Registered {
        path,
        file,
        added_to_registry,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    const REGISTRY: &str = "\
struct kbuild { int x; };

/* --- build includes (timer-extract registers here) --- */
/* --- end build includes --- */

static const struct kbuild *const kbuild_table[] = {
    /* --- build entries (timer-extract registers here) --- */
    /* --- end build entries --- */
};
";

    #[test]
    fn registers_include_and_entry_once() {
        let (first, changed) = register(REGISTRY, "6.12.69-x-gaaaa1111-ab1-4k", "6_12_69_x_gaaaa1111_ab1_4k").unwrap();
        assert!(changed);
        assert!(first.contains("#include \"kbuilds/6.12.69-x-gaaaa1111-ab1-4k.h\""));
        assert!(first.contains("    &kbuild_6_12_69_x_gaaaa1111_ab1_4k,"));
        assert!(is_registered(&first, "6_12_69_x_gaaaa1111_ab1_4k"));

        let (second, changed) = register(&first, "6.12.69-x-gaaaa1111-ab1-4k", "6_12_69_x_gaaaa1111_ab1_4k").unwrap();
        assert!(!changed);
        assert_eq!(first, second);
    }

    #[test]
    fn registration_keeps_the_markers_intact() {
        let (out, _) = register(REGISTRY, "rel-g22223333-4k", "rel_g22223333_4k").unwrap();
        let includes = out.find(INCLUDE_MARKER).unwrap();
        let entry_marker = out.find(ENTRY_MARKER).unwrap();
        assert!(out.find("#include \"kbuilds/rel-g22223333-4k.h\"").unwrap() < includes);
        assert!(out.find("    &kbuild_rel_g22223333_4k,").unwrap() < entry_marker);
        assert_eq!(out.matches(INCLUDE_MARKER).count(), 1);
        assert_eq!(out.matches(ENTRY_MARKER).count(), 1);
    }

    fn facts(release: &str) -> Facts {
        let mut symbols = std::collections::BTreeMap::new();
        for (name, value) in [
            ("SELINUX_STATE_STATIC", 0x51),
            ("PANIC_ON_WARN_STATIC", 0x52),
            ("ROOT_USER_STATIC", 0x53),
            ("INIT_USER_NS_STATIC", 0x54),
            ("INIT_UCOUNTS_STATIC", 0x55),
            ("INIT_GROUPS_STATIC", 0x56),
        ] {
            symbols.insert(name.to_string(), value);
        }
        Facts {
            release: Some(release.to_string()),
            text_base: 0x1000,
            sites: crate::derive::TraceSites {
                timer_site: 0x11,
                copy_process_site: 0x22,
            },
            data_symbols: symbols,
            layout: crate::derive::Layout {
                task_cred: 0x71,
                cred_uid: 0x72,
                sizeof_task: 0x1440,
                sizeof_cred: 0xb8,
                sizeof_kitimer: 0x100,
            },
            sizes: crate::derive::Sizes {
                timer_alloc: 0x100,
                cred_req: 0xb8,
                cred_alloc: 0xc0,
                task_bytes: 0x1440,
            },
            order: crate::derive::ExecOrder {
                calls: Vec::new(),
                cleanup_first: false,
            },
            del: crate::derive::TimerDelCheck {
                leaves_node_queued: true,
                null_path: 0,
                dequeues: false,
            },
            verdict: crate::derive::Verdict::Vulnerable,
        }
    }

    #[test]
    fn profile_file_matches_the_c_struct_field_order() {
        let text = render_profile(&facts("6.12.69-android16-6-gdeadbeef1234-ab1-4k")).unwrap();
        // only the data lines carry the initializer values
        let values: Vec<u64> = text
            .lines()
            .filter(|line| line.trim_start().starts_with("0x"))
            .flat_map(|line| line.split(','))
            .filter_map(|item| {
                item.trim()
                    .trim_end_matches(|ch| ch == 'U' || ch == 'L')
                    .strip_prefix("0x")
                    .and_then(|hex| u64::from_str_radix(hex, 16).ok())
            })
            .collect();
        let expected = [
            0x1011, // static_timer_site = text_base + timer_site
            0x11,   // timer_site_low21
            0x22,   // copy_process_low21
            0x51,   // selinux_state
            0x52,   // panic_on_warn
            0x53,   // root_user
            0x54,   // init_user_ns
            0x55,   // init_ucounts
            0x56,   // init_groups
            0x71,   // off_task_cred
            0xb8,   // cred_req
            0xc0,   // cred_alloc
            0x100,  // timer_alloc
            0x1440, // task_alloc_bytes
            0x72,   // cred_uid_off
        ];
        assert_eq!(values, expected);
        assert!(text.contains("kbuild_6_12_69_android16_6_gdeadbeef1234_ab1_4k"));
        assert!(text.contains("\"6.12.69-android16-6-gdeadbeef1234-ab1-4k\","));
    }

    #[test]
    fn missing_marker_is_an_error() {
        assert!(register("no markers here", "rel-g33334444-4k", "rel_g33334444_4k").is_err());
    }
}
